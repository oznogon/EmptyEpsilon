--[[ Generates constants for the names of ship templates and variants.

Reads every Lua file in the shiptemplates directory, records each template name
passed to setName() and each variant name passed to copy(), and writes a Lua
file containing one ST_* constant per name.

Usage:

    lua scripts/generate_ship_template_constants.lua [output_file]

If output_file is omitted, the constants are written to
shipTemplateConstants.lua next to this script.
]]

local script_path = arg and arg[0] or ""
local script_dir = script_path:match("^(.*[\\/])") or ""
local output_path = (arg and arg[1])
    or script_dir .. "ship_template_constants.lua"
local templates_path = script_dir

local templates = {}

local function record(kind, name)
    if not name or name == "" then
        error("Ship template with an empty name")
    end

    if templates[name] == nil then
        templates[name] = kind
    end
end

local template_mt = {}
template_mt.__index = function(_, key)
    if key == "setName" then
        return function(self, name)
            record("template", name)
            return self
        end
    elseif key == "copy" then
        return function(self, name)
            record("variant", name)
            return self
        end
    end

    return function(self, ...)
        return self
    end
end

function ShipTemplate()
    return setmetatable({}, template_mt)
end

function _(context, text)
    if text == nil then
        return context
    end

    return text
end

local function list_lua_files(directory)
    local ok, lfs = pcall(require, "lfs")
    if not ok then
        return nil
    end

    local files = {}
    local function walk(path)
        for entry in lfs.dir(path) do
            if entry ~= "." and entry ~= ".." then
                local entry_path = path .. "/" .. entry
                local attributes = lfs.attributes(entry_path)
                if attributes and attributes.mode == "directory" then
                    walk(entry_path)
                elseif entry:match("%.lua$") then
                    files[#files + 1] = entry_path
                end
            end
        end
    end

    walk(directory)
    table.sort(files)
    return files
end

local function load_templates()
    local files = list_lua_files(templates_path)
    if files then
        for _, path in ipairs(files) do
            dofile(path)
        end
        return
    end

    -- LuaFileSystem is not available; use the canonical template loader.
    local real_dofile = dofile
    require = function(path)
        real_dofile(script_dir .. path)
    end
    real_dofile(script_dir .. "shipTemplates.lua")
end

local function to_constant(name)
    local identifier = name:upper():gsub("[^%w%s]", ""):gsub("%s+", "_")
    return "ST_" .. identifier
end

local function quote(value)
    return '"' .. value:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
end

load_templates()

local constants = {}
local constant_names = {}
for name, kind in pairs(templates) do
    local constant = to_constant(name)
    if constant_names[constant] then
        error(
            string.format(
                "Constant %s is generated by both %q and %q",
                constant,
                constant_names[constant],
                name
            )
        )
    end

    constant_names[constant] = name
    constants[#constants + 1] = {
        constant = constant,
        name = name,
        kind = kind,
    }
end

table.sort(constants, function(a, b)
    return a.constant < b.constant
end)

if #constants == 0 then
    error("No ship templates found in " .. templates_path)
end

local output = io.open(output_path, "w")
if not output then
    error("Could not open " .. output_path .. " for writing")
end

output:write(
    "--[[ Ship template name constants\n",
    "\n",
    "Generated by generate_ship_template_constants.lua from the ship templates\n",
    "in the shiptemplates directory. Do not edit manually; rerun the generator\n",
    "instead.\n",
    "]]\n",
    "\n"
)

for _, entry in ipairs(constants) do
    output:write(entry.constant, " = ", quote(entry.name), "\n")
end

output:close()
print(
    string.format(
        "Wrote %d ship template constants to %s",
        #constants,
        output_path
    )
)
